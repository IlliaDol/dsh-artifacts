/**
 * Inline kit/*.js into lib/kit.js as exported strings.
 *
 * The plugin ships with `lib/` committed and no build step at install time, and
 * an artifact is one self-contained HTML document. So the kit is embedded here,
 * once, from its only source of truth.
 *
 * usage: node scripts/build-kit.mjs
 */
import fs from 'node:fs'
import path from 'node:path'

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..')
const read = (file) => fs.readFileSync(path.join(ROOT, file), 'utf8')
const guard = (source) => source.replace(/<\/script/gi, '<\\/script')

const parts = {
  KIT_CSS: guard(read('kit/artifacts.css')),
  KIT_VIZ: guard(read('kit/viz-kit.js')),
  KIT_3D: guard(read('kit/viz3d.js')),
  KIT_CHARTS: guard(read('kit/charts.js')),
}

/** Bridge the artifact tokens to the names the kit reads. */
const TOKENS = `:root{--vz-text:var(--text);--vz-dim:var(--text-2);--vz-faint:var(--muted);--vz-line:var(--border);--vz-surface:var(--surface);--vz-accent:var(--accent)}`

const out = `/**
 * Generated by scripts/build-kit.mjs — edit kit/*.js and rerun.
 *
 * The kit is embedded rather than served so every artifact is one
 * self-contained document that works from a route, an export or a file.
 */
${Object.entries(parts).map(([name, source]) => `export const ${name} = ${JSON.stringify(source)}`).join('\n')}

/** Token bridge: artifact variables to the names the kit reads. */
export const KIT_TOKENS = ${JSON.stringify(TOKENS)}

/**
 * The scripts an artifact needs before it can draw with VK, V3 or VC.
 * @returns {string} HTML injected before </body>
 */
export function kitScripts() {
  return \`<script>\${KIT_VIZ}</script>\\n<script>\${KIT_3D}</script>\\n<script>\${KIT_CHARTS}</script>\`
}

/** The chart stylesheet plus the token bridge. */
export const KIT_STYLE = \`\${KIT_CSS}\\n\${KIT_TOKENS}\`
`

fs.writeFileSync(path.join(ROOT, 'lib/kit.js'), out)
const size = Buffer.byteLength(out)
console.log(`wrote lib/kit.js (${(size / 1024).toFixed(1)} KB)`)
